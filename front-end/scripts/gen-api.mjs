// Regenerates the dashboard's copy of the crawler API contract:
//   src/lib/api/openapi.json  - the backend's OpenAPI schema
//   src/lib/api/schema.d.ts   - TypeScript types generated from it
// Run with `npm run gen:api`. Needs uv; the backend lives in ../python/backend.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const backend = join(root, "..", "python", "backend");
const outDir = join(root, "src", "lib", "api");

const dump =
  "import json; from crawler_api.main import create_app; " +
  "print(json.dumps(create_app().openapi(), indent=2))";

// Arguments as an array, no shell: the same quoting on Windows and Linux.
const result = spawnSync("uv", ["run", "--project", backend, "python", "-c", dump], {
  encoding: "utf-8",
});
if (result.error || result.status !== 0) {
  console.error(result.error ?? result.stderr);
  process.exit(1);
}

const schema = JSON.parse(result.stdout);
writeFileSync(join(outDir, "openapi.json"), JSON.stringify(schema, null, 2) + "\n");

const header =
  "// Generated by scripts/gen-api.mjs from the crawler API's OpenAPI schema. Do not edit.\n\n";
writeFileSync(join(outDir, "schema.d.ts"), header + astToString(await openapiTS(schema)));

console.log("Wrote src/lib/api/openapi.json and src/lib/api/schema.d.ts");
